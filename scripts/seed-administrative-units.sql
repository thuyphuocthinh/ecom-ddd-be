--   docker exec -i ecom_postgres psql -U root -d ecom_db < scripts/seed-administrative-units.sql
--
-- Where the data comes from (fetched 2026-10-10):
--   * provinces.open-api.vn, API v2 (34 provinces, 3,321 wards, codes of the administrative code table)
--   * checked against a second open data set, github.com/vietmap-company/vietnam_administrative_address
--     (also 3,321 wards): the ward and province names agree everywhere, except that it calls 11 wards of
--     Đồng Nai "Phường" where the main source (and a third set, github.com/zuydd/vn-geo) say "Xã";
--     the main source is followed.
--   * NOT checked against the legal documents themselves. Fix this file and run it again if a mistake shows up.
--
-- What was done to the data:
--   * "name" has no kind in front ("Ba Đình", not "Phường Ba Đình"); the kind is in "type" (WARD, COMMUNE,
--     SPECIAL_ZONE for wards; CITY, PROVINCE for provinces).
--   * Only the 6 centrally-run cities are CITY (codes 01 Hà Nội, 31 Hải Phòng, 46 Huế, 48 Đà Nẵng,
--     79 Hồ Chí Minh, 92 Cần Thơ); the source also calls Quảng Ninh, Bắc Ninh and Đồng Nai "city", which is wrong.
--   * Codes are text: 2 digits for a province, 5 digits for a ward. Spelling is kept as in the source
--     (for example the tone mark in "Hoà").

